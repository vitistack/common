// Command statusapply-gen generates a <Kind>StatusUpdater function for every
// kind in an applyconfiguration-gen package that has a status, so reconcilers
// can write:
//
//	patch := ac.NetworkNamespaceStatusUpdater(&nn)
//
// It must run after the apply configurations are generated.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"
)

const outputFile = "statusupdaters_gen.go"

var tmpl = template.Must(template.New("gen").Parse(`// Code generated by statusapply-gen. DO NOT EDIT.

package {{.Package}}

import (
	"github.com/vitistack/common/pkg/operator/statusapply"
	{{.APIAlias}} "{{.APIImport}}"
)
{{range .Kinds}}
// {{.}}StatusUpdater starts a status Patch for obj. See statusapply.For.
func {{.}}StatusUpdater(obj *{{$.APIAlias}}.{{.}}) *statusapply.Patch[*{{.}}StatusApplyConfiguration] {
	return statusapply.For(obj, {{.}}Status())
}
{{end}}`))

func main() {
	dir := flag.String("dir", "", "directory of the generated apply configuration package")
	apiImport := flag.String("api", "", "import path of the API types package")
	flag.Parse()
	if *dir == "" || *apiImport == "" {
		fmt.Fprintln(os.Stderr, "usage: statusapply-gen -dir <applyconfiguration package dir> -api <api types import path>")
		os.Exit(2)
	}
	if err := run(*dir, *apiImport); err != nil {
		fmt.Fprintln(os.Stderr, "statusapply-gen:", err)
		os.Exit(1)
	}
}

func run(dir, apiImport string) error {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool {
		return !strings.HasSuffix(fi.Name(), "_test.go") && fi.Name() != outputFile
	}, 0)
	if err != nil {
		return fmt.Errorf("parsing %s: %w", dir, err)
	}
	if len(pkgs) != 1 {
		return fmt.Errorf("expected one package in %s, found %d", dir, len(pkgs))
	}

	var pkgName string
	kinds := map[string]bool{}
	for name, pkg := range pkgs {
		pkgName = name
		for _, f := range pkg.Files {
			collectKinds(f, kinds)
		}
	}
	sorted := make([]string, 0, len(kinds))
	for k := range kinds {
		sorted = append(sorted, k)
	}
	sort.Strings(sorted)

	// Aliased so it cannot clash with the generated package's own name.
	apiAlias := "api" + filepath.Base(apiImport)
	var buf bytes.Buffer
	err = tmpl.Execute(&buf, map[string]any{
		"Package":   pkgName,
		"APIImport": apiImport,
		"APIAlias":  apiAlias,
		"Kinds":     sorted,
	})
	if err != nil {
		return fmt.Errorf("rendering: %w", err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("formatting: %w", err)
	}
	out := filepath.Join(dir, outputFile)
	if err := os.WriteFile(out, src, 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", out, err)
	}
	return nil
}

// collectKinds adds every Kind for which the file declares
// func (*KindApplyConfiguration) WithStatus(*KindStatusApplyConfiguration).
func collectKinds(f *ast.File, kinds map[string]bool) {
	for _, d := range f.Decls {
		fn, ok := d.(*ast.FuncDecl)
		if !ok || fn.Recv == nil || fn.Name.Name != "WithStatus" || len(fn.Recv.List) != 1 {
			continue
		}
		recv := typeName(fn.Recv.List[0].Type)
		kind, ok := strings.CutSuffix(recv, "ApplyConfiguration")
		if !ok || kind == "" || fn.Type.Params.NumFields() != 1 {
			continue
		}
		if typeName(fn.Type.Params.List[0].Type) == kind+"StatusApplyConfiguration" {
			kinds[kind] = true
		}
	}
}

func typeName(e ast.Expr) string {
	if s, ok := e.(*ast.StarExpr); ok {
		e = s.X
	}
	if id, ok := e.(*ast.Ident); ok {
		return id.Name
	}
	return ""
}
